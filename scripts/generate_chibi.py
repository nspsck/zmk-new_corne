#!/usr/bin/env python3
"""Convert the approved portrait to nice!view's LVGL 1-bit image format.

Requires ImageMagick 7 (`magick`) and Python 3; no Python packages are needed.
Run from any directory. Use --check to verify committed assets without writing.
"""

import argparse
from pathlib import Path
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/nice_view_chibi"
SOURCE = ASSETS / "sleepy-chibi-source.png"
PORTRAIT_WIDTH, PORTRAIT_HEIGHT = 68, 160
WIDTH, HEIGHT = PORTRAIT_HEIGHT, PORTRAIT_WIDTH


def magick(*args, data=None):
    return subprocess.run(
        ["magick", *map(str, args)], input=data, check=True, capture_output=True
    ).stdout


def generate():
    # Thicken fine outlines before shrinking. Leave the small sleep glyphs at
    # the top unthickened so they retain their white strokes.
    portrait = magick(
        SOURCE, "-alpha", "off", "-colorspace", "Gray",
        "-morphology", "Erode", "Disk:2",
        "-filter", "Lanczos", "-resize", "68x160!", "-threshold", "55%",
        "(", SOURCE, "-alpha", "off", "-colorspace", "Gray",
        "-filter", "Lanczos", "-resize", "68x160!", "-threshold", "55%",
        "-crop", "68x28+0+0", "+repage", ")",
        "-gravity", "NorthWest", "-compose", "Over", "-composite",
        "-type", "bilevel", "-strip",
        "-define", "png:bit-depth=1", "-define", "png:color-type=0", "PNG:-",
    )
    preview = magick(
        "PNG:-", "-scale", "408x960!", "-strip",
        "-define", "png:bit-depth=1", "-define", "png:color-type=0", "PNG:-",
        data=portrait,
    )

    # Upstream nice_view rotates portrait content clockwise into the panel's
    # native 160x68 framebuffer. Pre-rotate to avoid runtime canvas allocation.
    native = magick("PNG:-", "-rotate", "90", "-depth", "8", "gray:-", data=portrait)
    if len(native) != WIDTH * HEIGHT or set(native) != {0, 255}:
        raise ValueError("Expected a 160x68 image containing only black and white")

    # LVGL indexed images start with BGRA palette entries. Pixels are packed
    # left-to-right, most-significant bit first; each row occupies 20 bytes.
    palette = bytes((0, 0, 0, 255, 255, 255, 255, 255))
    bitmap = bytes(
        sum((native[start + bit] == 255) << (7 - bit) for bit in range(8))
        for start in range(0, len(native), 8)
    )
    pixels = palette + bitmap
    if len(pixels) != 1368:
        raise ValueError("Unexpected LVGL palette/bitmap size")
    rows = [
        "    " + ", ".join(f"0x{byte:02x}" for byte in pixels[start:start + 20]) + ","
        for start in range(0, len(pixels), 20)
    ]
    source = """/* Generated by scripts/generate_chibi.py; do not edit by hand.
 * Approved sleepy-chibi portrait, rotated clockwise for nice!view.
 */

#include <lvgl.h>

static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t sleepy_chibi_map[] = {
""" + "\n".join(rows) + """
};

const lv_img_dsc_t sleepy_chibi = {
    .header.always_zero = 0,
    .header.w = 160,
    .header.h = 68,
    .header.cf = LV_IMG_CF_INDEXED_1BIT,
    .data_size = sizeof(sleepy_chibi_map),
    .data = sleepy_chibi_map,
};
"""
    return {
        ASSETS / "sleepy-chibi-68x160.png": portrait,
        ASSETS / "sleepy-chibi-preview.png": preview,
        ROOT / "boards/shields/nice_view_chibi/sleepy_chibi.c": source.encode(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify assets without changing them")
    args = parser.parse_args()
    try:
        outputs = generate()
    except FileNotFoundError:
        parser.exit(1, "ImageMagick 7 is required: install it so `magick` is on PATH.\n")
    except subprocess.CalledProcessError as error:
        parser.exit(1, error.stderr.decode(errors="replace"))
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            print(path.relative_to(ROOT))
    if stale:
        parser.exit(1, "Regenerate assets with python3 scripts/generate_chibi.py:\n" + "\n".join(stale) + "\n")
    if args.check:
        print("Portrait, preview, and 1,368-byte LVGL bitmap match the approved source conversion.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
